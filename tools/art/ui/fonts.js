export function smallGlyphs() {
  const map = new Map();
  for (const line of SMALL.split('\n')) {
    if (line.length < 3) continue;
    let ch = line[0];
    let rest = line.slice(2);
    if (line.startsWith('\\\\')) {
      ch = '\\';
      rest = line.slice(3);
    }
    map.set(ch, rest.split('|'));
  }
  return map;
}

function grid(cellW, cellH, cols, count) {
  return new PixelCanvas(cellW * cols, cellH * Math.ceil(count / cols));
}

/** Small 5x7 font, ASCII 32..126, gray ramp (lighter at the top). */
function smallFont() {
  const g = smallGlyphs();
  const cw = 6;
  const ch = 8;
  const c = grid(cw, ch, 16, 95);
  for (let code = 32; code < 127; code++) {
    const rows = g.get(String.fromCharCode(code));
    if (!rows) continue;
    const i = code - 32;
    const ox = (i % 16) * cw;
    const oy = Math.floor(i / 16) * ch;
    rows.forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '#') c.set(ox + x, oy + y, C('gray', 1 - y * 0.06));
    });
  }
  return c;
}

/** Chunky 2x font with a gradient, outline and shadow (menus, titles, HUD numbers). */
function bigFont({ ramp = 'blood', top = 1, bottom = 0.45, upper = true, chars = null } = {}) {
  const g = smallGlyphs();
  const cw = 13;
  const ch = 17;
  const list = chars ?? Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i));
  const c = grid(cw, ch, 16, list.length);
  list.forEach((char, i) => {
    let rows = g.get(upper ? char.toUpperCase() : char);
    if (!rows) return;
    const cell = new PixelCanvas(cw, ch);
    rows.forEach((row, y) => {
      for (let x = 0; x < 5; x++) {
        if (row[x] !== '#') continue;
        for (let sy = 0; sy < 2; sy++) {
          const t = top + (bottom - top) * ((y * 2 + sy) / 13);
          const col = C(ramp, t);
          cell.set(1 + x * 2, 1 + y * 2 + sy, col);
          cell.set(2 + x * 2, 1 + y * 2 + sy, col);
        }
      }
    });
    // Highlight on top edges of strokes.
    const lit = cell.clone();
    lit.eachOpaque((x, y, p) => (!cell.opaque(x, y - 1) ? C(ramp === 'blood' ? 'orange' : ramp, 1) : p));
    lit.outline(C('gray', 0.02));
    // Drop shadow.
    const out = new PixelCanvas(cw, ch);
    lit.eachOpaque((x, y) => {
      out.set(x + 1, y + 1, C('gray', 0.01));
    });
    out.blit(lit, 0, 0);
    c.blit(out, (i % 16) * cw, Math.floor(i / 16) * ch);
  });
  return c;
}

/** 3x5 tiny font (digits and caps) for the ammo tally and ARMS panel. */
function tinyFont() {
  const cw = 4;
  const ch = 6;
  const c = grid(cw, ch, 16, 64);
  for (let code = 32; code < 96; code++) {
    const g = TINY[String.fromCharCode(code)];
    if (!g) continue;
    const i = code - 32;
    const ox = (i % 16) * cw;
    const oy = Math.floor(i / 16) * ch;
    for (let y = 0; y < 5; y++) for (let x = 0; x < 3; x++) if (g[y * 3 + x] === '1') c.set(ox + x, oy + y, C('gray', 0.95 - y * 0.05));
  }
  return c;
}

